#include <stdio.h>
int main()
{
    int a=10;
    printf("initial value of  a=%d\n",a);
    a=+5;
    printf("after a+=:%d\n",a);
    a-=3;
    printf("after a-=:%d\n",a);
    a*=2;
    printf("after a*=:%d\n",a);
    a/=4;
    printf("after a/=:%d\n",a);
    a%=4;
    printf("after a%%=:%d\n",a);
return 0;


}
